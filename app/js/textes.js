// Renvoie le texte d'une clé, avec les valeurs {nom} remplacées.
export function t(cle, valeurs) {
  let texte = T[cle];
  if (texte === undefined) return cle;
  if (valeurs) {
    Object.keys(valeurs).forEach((nom) => { texte = texte.split("{" + nom + "}").join(String(valeurs[nom])); });
  }
  return texte;
}

export function texteDuree(minutes) { return t("duree", { n: minutes }); }
